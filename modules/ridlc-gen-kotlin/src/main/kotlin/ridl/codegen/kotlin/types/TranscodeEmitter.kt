package ridl.codegen.kotlin.types

import com.squareup.kotlinpoet.ClassName
import com.squareup.kotlinpoet.FileSpec
import com.squareup.kotlinpoet.FunSpec
import com.squareup.kotlinpoet.INT
import com.squareup.kotlinpoet.KModifier
import com.squareup.kotlinpoet.MemberName
import com.squareup.kotlinpoet.TypeSpec
import ridl.codegen.kotlin.PLUGIN
import ridl.codegen.kotlin.WireEncoding
import ridl.codegen.v1.ModelOuterClass.Visibility

private val TRANSCODE = MemberName("ridl.rt.payload", "transcode")
private val TRANSCODE_ERROR = ClassName("ridl.rt.payload", "TranscodeError")
private val TC_BYTE_BUFFER = ClassName("java.nio", "ByteBuffer")

/**
 * A generated type that carries a `Payload` object, [codec], for one
 * encoding. A codec emitter reports one per codec object it writes, so the
 * transcode functions follow the emitter's own rule, as the Rust backend's
 * `transcode::PayloadOwner` does.
 */
class PayloadOwner(val name: String, val visibility: Visibility, val codec: ClassName)

/**
 * `Transcode.kt` (#136): for each type that has a `Payload` object under at
 * least two of the selected encodings, `object <Type>Transcode` with one
 * function per ordered pair of distinct encodings, `<source>To<Target>`, whose
 * body is `ridl.rt.payload.transcode` over the two codecs. The Rust backend's
 * `transcode.rs`, in Kotlin: the same types, pairs and order.
 *
 * [owners] holds one list per selected encoding, in the order the manifest
 * names them. The types come in the first list's order, then those only a
 * later list has; the pairs, in that order of sources then of targets.
 */
class TranscodeEmitter(
    private val pkg: String,
    private val dotted: String,
    private val owners: List<Pair<WireEncoding, List<PayloadOwner>>>,
) {
    fun emit(): EmittedTypes {
        val path = pkg.replace('.', '/') + "/Transcode.kt"
        val file = FileSpec.builder(pkg, "Transcode").jvmName("Transcode")
        val claims = mutableListOf<Claim>()
        for (owner in owners.flatMap { it.second }.distinctBy { it.name }) {
            val functions = pairs(owner.name)
            if (functions.isEmpty()) continue
            claims += Claim("${owner.name}Transcode", "the transcode functions of `${owner.name}`")
            val type = TypeSpec.objectBuilder("${owner.name}Transcode")
                .addKdoc("The transcode functions of [%T]: each re-encodes one encoding's payload as another's.", ClassName(pkg, owner.name))
                .addFunctions(functions)
            if (owner.visibility == Visibility.VISIBILITY_INTERNAL) type.addModifiers(KModifier.INTERNAL)
            file.addType(type.build())
        }
        if (claims.isEmpty()) return EmittedTypes(path, null, emptyList())
        file.addFileComment("Generated by %L from `%L`. Do not edit.", PLUGIN, dotted)
        return EmittedTypes(path, file.build().toString(), emptyList(), claims)
    }

    /** The functions of [name], one per ordered pair of distinct encodings that both have its codec. */
    private fun pairs(name: String): List<FunSpec> {
        val codecs = owners.mapNotNull { (encoding, list) -> list.firstOrNull { it.name == name }?.let { encoding to it.codec } }
        return codecs.flatMap { source -> codecs.filter { it.first != source.first }.map { target -> function(source, target) } }
    }

    private fun function(source: Pair<WireEncoding, ClassName>, target: Pair<WireEncoding, ClassName>): FunSpec {
        val (from, to) = source.first.key to target.first.key
        return FunSpec.builder(from + "To" + to.replaceFirstChar(Char::uppercaseChar))
            .addKdoc(
                "Re-encodes a %L payload as a %L payload.\n\n" +
                    "The bytes from [bytes]' position to its limit are verified as %L, decoded, and encoded as %L " +
                    "into [out] from its position, which advances past the bytes written; returns their number. " +
                    "The body is [%M].\n\n" +
                    "@throws %T when the bytes do not verify, or the value does not encode into [out].",
                from, to, from, to, TRANSCODE, TRANSCODE_ERROR,
            )
            .addParameter("bytes", TC_BYTE_BUFFER)
            .addParameter("out", TC_BYTE_BUFFER)
            .returns(INT)
            .addStatement("return %M(%T, %T, bytes, out)", TRANSCODE, source.second, target.second)
            .build()
    }
}
