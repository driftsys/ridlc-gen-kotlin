package ridl.codegen.kotlin.types

import com.squareup.kotlinpoet.FileSpec
import com.squareup.kotlinpoet.INT
import com.squareup.kotlinpoet.KModifier
import com.squareup.kotlinpoet.PropertySpec
import com.squareup.kotlinpoet.TypeSpec
import ridl.codegen.kotlin.PLUGIN
import ridl.codegen.v1.DeploymentOuterClass.Deployment
import java.util.TreeMap

/** The object the instance constants of the system are nested in. */
internal const val INSTANCES: String = "Instances_"

/** What [InstancesEmitter.emit] produced: the file, none, or the refusals that replace it. */
class EmittedInstances(val path: String, val text: String?, val errors: List<String>)

/**
 * `Instances.kt`: one constant for the number of each instance of the system
 * (rsdl reference §7), nested in `object Instances_` along the path the Rust
 * backend's `instances` module gives it
 * (`crates/ridl-backend-rust/src/instances.rs` at the pinned release): one
 * object per segment of the component's qualified name in snake case, and
 * the instance name in screaming snake case, both sorted by name.
 *
 * The numbers are read from the request's deployment section, the one place
 * a plugin finds them (#137). A deployment places every instance of the
 * system (RSDL-701), so the section carries every number the Rust module
 * does, whichever deployment is selected. The Rust module is written from the
 * system itself, and the two differ only when the build selects no
 * deployment: there is then no section, and no file. An instance the section
 * carries with the number 0, which the system IR does not number, has no
 * constant, as in the Rust module.
 */
class InstancesEmitter(private val deployment: Deployment?, private val kotlinPackage: String) {
    /** A module of the Rust tree: its constants and the modules below it, each by name. */
    private class Node {
        val children = TreeMap<String, Node>()
        val constants = TreeMap<String, Constant>()
    }

    /** One constant: its lock key, its value, and whether no lock entry holds it yet. */
    private class Constant(val key: String, val number: Int, val provisional: Boolean)

    fun emit(): EmittedInstances {
        val path = kotlinPackage.replace('.', '/') + "/Instances.kt"
        val numbered = deployment?.instancesList.orEmpty().filter { it.number != 0 }
        if (numbered.isEmpty()) return EmittedInstances(path, null, emptyList())
        val root = Node()
        val errors = mutableListOf<String>()
        for (instance in numbered) {
            val node = instance.component.split('.').fold(root) { node, segment ->
                node.children.getOrPut(snakeCase(segment)) { Node() }
            }
            val name = snakeCase(instance.instance).uppercase()
            val key = "${instance.component}/${instance.instance}"
            val existing = node.constants[name]
            when {
                existing == null -> node.constants[name] = Constant(key, instance.number, instance.provisional)
                // One instance placed twice by the section is one constant.
                existing.key == key -> {}
                else -> errors += "$PLUGIN: the instances `${existing.key}` and `$key` both map to the constant " +
                    "`$name` of `$INSTANCES`"
            }
        }
        if (errors.isNotEmpty()) return EmittedInstances(path, null, errors)
        val instances = TypeSpec.objectBuilder(INSTANCES)
            .addKdoc(
                "The number of every instance of system `%L`, from `instances.lock`, as deployment `%L` carries it.",
                deployment!!.system,
                deployment.name,
            )
        members(root, instances)
        val file = FileSpec.builder(kotlinPackage, "Instances")
            .addFileComment("Generated by %L. Do not edit.", PLUGIN)
            .addType(instances.build())
            .build()
        return EmittedInstances(path, file.toString(), emptyList())
    }

    private fun members(node: Node, into: TypeSpec.Builder) {
        for ((name, constant) in node.constants) {
            val property = PropertySpec.builder(name, INT, KModifier.CONST)
                .initializer("%L", constant.number)
                .addKdoc("`%L` in `instances.lock`.", constant.key)
            if (constant.provisional) {
                property.addKdoc("\n\nProvisional: no entry of `instances.lock` holds this number yet, and `ridl lock` writes it.")
            }
            into.addProperty(property.build())
        }
        for ((segment, child) in node.children) {
            val inner = TypeSpec.objectBuilder(segment)
            members(child, inner)
            into.addType(inner.build())
        }
    }
}

/**
 * `ridl_ir::name::snake_case` at the pinned release: an `_` before an upper
 * case letter that follows a lower case letter or a digit, or that starts a
 * word after an acronym, and every letter in lower case. Not injective; the
 * emitter refuses two instances it maps to one constant.
 */
internal fun snakeCase(name: String): String = buildString {
    for ((index, current) in name.withIndex()) {
        if (current.isUpperCase() && index > 0) {
            val previous = name[index - 1]
            val nextLower = name.getOrNull(index + 1)?.isLowerCase() == true
            if (previous.isLowerCase() || previous.isNumeric() || (previous.isUpperCase() && nextLower)) append('_')
        }
        append(current.lowercase())
    }
}

/** Rust's `char::is_numeric`: the general categories `Nd`, `Nl` and `No`. */
private fun Char.isNumeric(): Boolean =
    category == CharCategory.DECIMAL_DIGIT_NUMBER || category == CharCategory.LETTER_NUMBER || category == CharCategory.OTHER_NUMBER
